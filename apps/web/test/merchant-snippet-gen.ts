#!/usr/bin/env bun
/**
 * Writes apps/web/src/routes/merchant/snippet.generated.ts from the two files the console's own
 * checkout runs (examples/whitechain). The merchant screen's "integrate this" block renders that
 * module, and apps/web/test/merchant-snippet.test.ts fails whenever the two drift apart.
 *
 *   bun apps/web/test/merchant-snippet-gen.ts
 *
 * One change is made for display, and only one: each workspace import is shown under the name the
 * v0.1.0 release publishes it as (K3, scripts/release/surface.ts). The workspace names are
 * @countersign/*, and on npm that scope belongs to another project, so a reader who copied them
 * and installed would run someone else's code.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..", "..", "..");
export const SNIPPET_FILES = {
  merchant: "examples/whitechain/checkout-merchant.ts",
  customer: "examples/whitechain/checkout-customer.ts",
} as const;

/**
 * Each workspace specifier the snippets import, and its published name. The release does not
 * publish the relay's root, only ./paywall, ./pay-fetch and ./browser, so whitechainPaywall
 * (packages/relay/src/paywall.ts) is shown from ./paywall.
 */
export const PUBLISHED_SPECIFIERS: Readonly<Record<string, string>> = {
  "@countersign/relay": "@countersign-hub/relay/paywall",
  "@countersign/relay/browser": "@countersign-hub/relay/browser",
};

const SPECIFIER = /(from\s+|import\s*\(\s*)(["'])(@countersign\/[^"']+)\2/g;

/** The file as shown: identical except that each import names the published package. */
export function displayedSource(source: string, file: string): string {
  return source.replace(SPECIFIER, (_match, lead: string, quote: string, specifier: string) => {
    const published = PUBLISHED_SPECIFIERS[specifier];
    if (!published) {
      throw new Error(`${file} imports ${specifier}, which has no published name in PUBLISHED_SPECIFIERS.`);
    }
    return `${lead}${quote}${published}${quote}`;
  });
}

/** The inverse, so a test can show the shown file is the running file and nothing else. */
export function workspaceSource(displayed: string): string {
  const back = new Map(Object.entries(PUBLISHED_SPECIFIERS).map(([workspace, published]) => [published, workspace]));
  return displayed.replace(/(from\s+|import\s*\(\s*)(["'])(@countersign-hub\/[^"']+)\2/g, (match, lead: string, quote: string, specifier: string) => {
    const workspace = back.get(specifier);
    return workspace ? `${lead}${quote}${workspace}${quote}` : match;
  });
}

export function snippetModule(): string {
  const merchant = displayedSource(readFileSync(join(root, SNIPPET_FILES.merchant), "utf8"), SNIPPET_FILES.merchant);
  const customer = displayedSource(readFileSync(join(root, SNIPPET_FILES.customer), "utf8"), SNIPPET_FILES.customer);
  return [
    "// Generated by apps/web/test/merchant-snippet-gen.ts from the files the console's checkout runs,",
    "// with each import shown under its published name (@countersign-hub). Do not edit:",
    "// apps/web/test/merchant-snippet.test.ts fails if this ever differs from them.",
    "",
    `export const SNIPPET_PATHS = ${JSON.stringify(SNIPPET_FILES)} as const;`,
    "",
    `export const MERCHANT_SNIPPET = ${JSON.stringify(merchant)};`,
    "",
    `export const CUSTOMER_SNIPPET = ${JSON.stringify(customer)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const out = join(root, "apps/web/src/routes/merchant/snippet.generated.ts");
  writeFileSync(out, snippetModule());
  console.log(`wrote ${out}`);
}
