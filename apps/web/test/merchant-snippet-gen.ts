#!/usr/bin/env bun
/**
 * Writes apps/web/src/routes/merchant/snippet.generated.ts from the two files the console's own
 * checkout runs (examples/whitechain). The merchant screen's "integrate this" block renders that
 * module, and apps/web/test/merchant-snippet.test.ts fails whenever the two drift apart.
 *
 *   bun apps/web/test/merchant-snippet-gen.ts
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..", "..", "..");
export const SNIPPET_FILES = {
  merchant: "examples/whitechain/checkout-merchant.ts",
  customer: "examples/whitechain/checkout-customer.ts",
} as const;

export function snippetModule(): string {
  const merchant = readFileSync(join(root, SNIPPET_FILES.merchant), "utf8");
  const customer = readFileSync(join(root, SNIPPET_FILES.customer), "utf8");
  return [
    "// Generated by apps/web/test/merchant-snippet-gen.ts from the files the console's checkout runs.",
    "// Do not edit: apps/web/test/merchant-snippet.test.ts fails if this ever differs from them.",
    "",
    `export const SNIPPET_PATHS = ${JSON.stringify(SNIPPET_FILES)} as const;`,
    "",
    `export const MERCHANT_SNIPPET = ${JSON.stringify(merchant)};`,
    "",
    `export const CUSTOMER_SNIPPET = ${JSON.stringify(customer)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const out = join(root, "apps/web/src/routes/merchant/snippet.generated.ts");
  writeFileSync(out, snippetModule());
  console.log(`wrote ${out}`);
}
